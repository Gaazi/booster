"""Generate a ready-to-edit Booster adapter inside a host project."""

import json
from pathlib import Path
from typing import Iterable

ADAPTER_NAME = "booster_plugin.py"
CONFIG_NAME = "booster.json"
DEFAULT_INCLUDE = ("/static/",)
DEFAULT_EXCLUDE = ("/media/", "/api/")

TEMPLATE = '''"""Booster plugin adapter - generated by `booster init`.

Register it before the other middleware so Booster stays the innermost layer:

    from {module} import attach_booster
    attach_booster(app)

Keep only genuinely public routes in the policy. Personalised pages, uploads
and APIs must stay out. When the project contains a booster.json file, that
declarative configuration wins over the prefixes below.
"""

import logging
from pathlib import Path
from typing import Any, Optional

import booster

logger = logging.getLogger(__name__)

CONFIG_PATH = Path(__file__).with_name("{config}")
CACHEABLE_PREFIXES = {include}
EXCLUDED_PREFIXES = {exclude}


def load_config() -> Optional[Any]:
    """Read the site configuration when the project declares one."""
    if CONFIG_PATH.exists():
        return booster.SiteConfig.from_file(CONFIG_PATH)
    return None


def build_cache_policy() -> Any:
    """Build the route policy for this site."""
    config = load_config()
    if config is not None:
        return config.cache_policy()
    return booster.CachePolicy(
        include_paths=CACHEABLE_PREFIXES,
        exclude_paths=EXCLUDED_PREFIXES,
    )


def attach_booster(app: Any) -> Optional[Any]:
    """Register Booster as the innermost middleware with the site policy."""
    config = load_config()
    options = config.attach_options() if config is not None else {{
        "cache_policy": build_cache_policy(),
        "enable_compression": False,
        "enable_minification": False,
        "max_cache_bytes": 8 * 1024 * 1024,
        "cache_ttl": 300,
    }}
    try:
        return booster.attach(app, **options)
    except (ValueError, RuntimeError) as exc:
        logger.warning("Booster plugin was not attached: %s", exc)
        return None
'''


def render_paths(paths: Iterable[str]) -> str:
    """Render a path tuple for the generated module."""
    values = list(paths)
    body = ", ".join(f'"{path}"' for path in values)
    return "(" + body + ("," if len(values) == 1 else "") + ")"


def render_adapter(include: Iterable[str], exclude: Iterable[str], module: str = ADAPTER_NAME[:-3]) -> str:
    """Render the adapter source for the requested route policy."""
    return TEMPLATE.format(include=render_paths(include), exclude=render_paths(exclude),
                           module=module, config=CONFIG_NAME)


def write_adapter(directory: Path, include: Iterable[str], exclude: Iterable[str],
                  force: bool = False) -> Path:
    """Write the adapter into a host project without overwriting existing work."""
    target = directory / ADAPTER_NAME
    if target.exists() and not force:
        raise FileExistsError(f"{target} already exists; pass force to replace it")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_adapter(include, exclude), encoding="utf-8")
    return target


def write_config(directory: Path, include: Iterable[str], exclude: Iterable[str],
                 force: bool = False) -> Path:
    """Write the matching JSON site configuration into a host project."""
    target = directory / CONFIG_NAME
    if target.exists() and not force:
        raise FileExistsError(f"{target} already exists; pass force to replace it")
    document = {
        "include_paths": list(include),
        "exclude_paths": list(exclude),
        "cache_ttl": 300,
        "max_cache_bytes": 8 * 1024 * 1024,
        "enable_compression": False,
        "enable_minification": False,
    }
    target.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    return target
