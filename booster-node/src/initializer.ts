/** Generate a ready-to-edit Booster middleware adapter inside a host project. */
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

export const ADAPTER_NAME = "booster_plugin.ts";
export const CONFIG_NAME = "booster.json";
export const DEFAULT_INCLUDE = ["/static/"];
export const DEFAULT_EXCLUDE = ["/media/", "/api/"];

const TEMPLATE = `/** Booster middleware adapter - generated by \`booster-node init\`.

Register it before the routes you want to accelerate, and keep authorization,
host validation and CORS outside it:

    import {buildMiddleware} from "./booster_plugin";

    app.use(buildMiddleware());

Keep only genuinely public routes in the policy. Personalised pages, uploads
and APIs must stay out. When the project contains a booster.json file, that
declarative configuration wins over the prefixes below.
 */

import {existsSync} from "node:fs";
import {join} from "node:path";
import {booster, loadSiteConfig, optionsFrom} from "booster-node";
import type {BoosterMiddleware} from "booster-node";

const CONFIG_PATH = join(process.cwd(), "\${config}");
const INCLUDE_PATHS = \${include};
const EXCLUDE_PATHS = \${exclude};

/** Build the middleware for this site from its configuration or its prefixes. */
export function buildMiddleware(): BoosterMiddleware {
  if (existsSync(CONFIG_PATH)) return booster(optionsFrom(loadSiteConfig(CONFIG_PATH)));
  return booster({includePaths: INCLUDE_PATHS, excludePaths: EXCLUDE_PATHS});
}
`;

/** Render a path array for the generated module. */
export function renderPaths(paths: string[]): string {
  return "[" + paths.map(path => JSON.stringify(path)).join(", ") + "]";
}

/** Render the adapter source for the requested route policy. */
export function renderAdapter(include: string[], exclude: string[]): string {
  return TEMPLATE
    .replace("${include}", renderPaths(include))
    .replace("${exclude}", renderPaths(exclude))
    .replace("${config}", CONFIG_NAME);
}

/** Write the adapter into a host project without overwriting existing work. */
export function writeAdapter(directory: string, include: string[], exclude: string[],
                            force = false): string {
  const target = join(directory, ADAPTER_NAME);
  if (existsSync(target) && !force) {
    throw new Error(`${target} already exists; pass force to replace it`);
  }
  mkdirSync(directory, {recursive: true});
  writeFileSync(target, renderAdapter(include, exclude), "utf8");
  return target;
}

/** Write the matching JSON site configuration into a host project. */
export function writeConfig(directory: string, include: string[], exclude: string[],
                            force = false): string {
  const target = join(directory, CONFIG_NAME);
  if (existsSync(target) && !force) {
    throw new Error(`${target} already exists; pass force to replace it`);
  }
  mkdirSync(directory, {recursive: true});
  const document = {
    includePaths: include,
    excludePaths: exclude,
    ttl: 300,
    maxCacheBytes: 8 * 1024 * 1024,
    compressDynamic: false,
  };
  writeFileSync(target, JSON.stringify(document, null, 2) + "\n", "utf8");
  return target;
}
